CREATE TABLE `turing_papers` (
	`id` int AUTO_INCREMENT NOT NULL,
	`paperNumber` varchar(16) NOT NULL,
	`title` varchar(512) NOT NULL,
	`subtitle` text,
	`author` varchar(256) NOT NULL DEFAULT 'Ir. Nigel T. Dearden, CEng MICE',
	`block` int,
	`paperDate` varchar(32),
	`cdnUrlText` text,
	`cdnUrlCover` text,
	`cdnUrlPdf` text,
	`wordCount` int,
	`contentHash` varchar(64),
	`fileSize` int,
	`publishedOn` varchar(32),
	`verificationStatus` enum('VERIFIED','PARTIAL','UNVERIFIED','MISSING') NOT NULL DEFAULT 'MISSING',
	`lastVerified` timestamp,
	`notes` text,
	`series` varchar(32) NOT NULL DEFAULT 'memorial',
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `turing_papers_id` PRIMARY KEY(`id`),
	CONSTRAINT `turing_papers_paperNumber_unique` UNIQUE(`paperNumber`)
);
